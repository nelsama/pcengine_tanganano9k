#!/usr/bin/env bash
# menu/build.sh : menu.c -> menu.hex + src/board/menu_cfg.vh (cc65)
set -euo pipefail
cd "$(dirname "$0")"; B=${CC65:-/d/cc65/bin}; O=../build/menu; mkdir -p $O
$B/cc65 -t none --cpu huc6280 -Oirs -Cl -o $O/menu.s menu.c
$B/cc65 -t none --cpu huc6280 -Oirs -Cl --code-name FATCODE -o $O/fat.s fat.c
for f in menu fat; do $B/ca65 --cpu huc6280 -o $O/$f.o $O/$f.s; done
for f in crt0 font; do $B/ca65 --cpu huc6280 -o $O/$f.o $f.s; done
$B/ld65 -C menu.cfg -m $O/menu.map -o $O/menu.bin $O/crt0.o $O/menu.o $O/fat.o $O/font.o $B/../lib/pce.lib
/c/msys64/ucrt64/bin/python -c "
import os
d=open('$O/menu.bin','rb').read(); assert len(d)==16384
d=d[8192:]+d[:8192]                       # bank 0 = \$E000
open('menu.hex','w',newline='\n').write('\n'.join('%02x'%x for x in d)+'\n')
p=os.getcwd().replace(chr(92),'/')
open('../src/board/menu_cfg.vh','w',newline='\n').write('// generated by menu/build.sh\n\`define MENU_HEX \"%s/menu.hex\"\n'%p)
"
grep -A14 'Segment list' $O/menu.map
